/**
 * White logos for the founder portfolio carousel (2026-11-17) that the site did not have yet (universities, former
 * employers, some clients and startups): cut out of the slides supplied by the team (assets-src/portfolio/slide-N.png,
 * boxes in assets-src/portfolio/crops.json), made pure white on transparent and upscaled 3× with smooth edges.
 * They come from screenshots: replace a crop with the official file when available (same name in public/brand/portfolio).
 * Writes public/brand/portfolio/<name>.webp and content/data/portfolio-logo-sizes.ts.
 * Run: node scripts/generate-portfolio-logos.cjs
 */
/* eslint-disable @typescript-eslint/no-require-imports -- plain Node script */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const root = path.join(__dirname, '..');
const src = path.join(root, 'assets-src', 'portfolio');
const outDir = path.join(root, 'public', 'brand', 'portfolio');
const SCALE = 3;
// distance from white (255 − darkest channel) → alpha: light tints (yellow, pale grey) still read as solid
const LOW = 14;
const HIGH = 96;

(async () => {
  fs.mkdirSync(outDir, { recursive: true });
  const crops = JSON.parse(fs.readFileSync(path.join(src, 'crops.json'), 'utf8'));
  const sizes = {};
  const tone = new Set(crops.tone ?? []);
  for (const [name, spec] of Object.entries(crops)) {
    if (name.startsWith('_') || name === 'tone') continue;
    const [slide, left, top, width, height, erase = []] = spec;
    const white = erase.map(([x, y, w, h]) => ({
      input: { create: { width: w, height: h, channels: 3, background: '#ffffff' } },
      left: x,
      top: y,
    }));
    // erase boxes are painted at the crop's own scale, before upscaling
    const cropped = await sharp(path.join(src, `slide-${slide}.png`)).extract({ left, top, width, height }).removeAlpha().png().toBuffer();
    const cleaned = white.length ? await sharp(cropped).composite(white).png().toBuffer() : cropped;
    const { data, info } = await sharp(cleaned)
      .resize({ width: width * SCALE, height: height * SCALE, kernel: 'lanczos3' })
      .removeAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    const n = info.width * info.height;
    const out = Buffer.alloc(n * 4, 255);
    const lum = (i) => 0.299 * data[i * 3] + 0.587 * data[i * 3 + 1] + 0.114 * data[i * 3 + 2];
    // tonal mode: the darkest pixel becomes fully opaque, lighter details stay see-through
    let darkest = 255;
    if (tone.has(name)) for (let i = 0; i < n; i++) darkest = Math.min(darkest, lum(i));
    for (let i = 0; i < n; i++) {
      const a = tone.has(name)
        ? (255 - lum(i) - LOW) / (255 - darkest - LOW)
        : (255 - Math.min(data[i * 3], data[i * 3 + 1], data[i * 3 + 2]) - LOW) / (HIGH - LOW);
      out[i * 4 + 3] = Math.max(0, Math.min(255, Math.round(a * 255)));
    }
    const { data: webp, info: o } = await sharp(out, { raw: { width: info.width, height: info.height, channels: 4 } })
      .trim()
      .webp({ quality: 92, alphaQuality: 100 })
      .toBuffer({ resolveWithObject: true });
    fs.writeFileSync(path.join(outDir, `${name}.webp`), webp);
    // ink density (0–1), as in the other logo tables: lets logoBox() give every logo the same visual weight
    const alpha = await sharp(webp).ensureAlpha().extractChannel(3).raw().toBuffer();
    let sum = 0;
    for (const v of alpha) sum += v;
    sizes[name] = [o.width, o.height, Math.round((sum / (255 * alpha.length)) * 1000) / 1000];
  }
  const rows = Object.entries(sizes).map(([k, v]) => `  ${/^[a-z0-9]+$/.test(k) ? k : `'${k}'`}: [${v.join(', ')}],`);
  fs.writeFileSync(
    path.join(root, 'content', 'data', 'portfolio-logo-sizes.ts'),
    `/** Generated by scripts/generate-portfolio-logos.cjs — do not edit. Size (px) and ink density (0–1) of each white logo in /brand/portfolio. */\nexport const portfolioLogoSizes: Record<string, [number, number, number]> = {\n${rows.join('\n')}\n};\n`,
  );
  console.log(Object.keys(sizes).length, 'logos');
})();
